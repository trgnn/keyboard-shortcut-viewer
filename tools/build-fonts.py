#!/usr/bin/env python3
"""Build the site's self-hosted fonts from their official releases (checksums pinned).

Inter, the key-label font: one source gives both outputs, so the DOM, the canvas
exports and the flattened SVG export all draw the very same glyphs:
  site/fonts/Inter-<weight>.woff2   webfont for the keys and the canvas (family "KSV Inter")
  site/glyphs.js                    outlines + advances, read by the SVG export (window.KSV_GLYPHS)
Layout features (kerning, contextual alternates) are dropped from its subset: every
glyph then renders from the character alone, which is what the outline table can
reproduce.

JetBrains Mono, the UI's mono font (labels, controls, footer):
  site/fonts/JetBrainsMono-<weight>.woff2

Each family's SIL Open Font License goes next to it (site/fonts/<Family>-LICENSE.txt).
Re-run after changing a weight or a character set.

  python3 -m venv /tmp/ksv-venv && /tmp/ksv-venv/bin/pip install fonttools brotli
  /tmp/ksv-venv/bin/python tools/build-fonts.py
"""
import hashlib, io, json, os, pathlib, urllib.request, zipfile

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont

INTER = ('https://github.com/rsms/inter/releases/download/v4.1/Inter-4.1.zip',
         '9883fdd4a49d4fb66bd8177ba6625ef9a64aa45899767dde3d36aa425756b11e')
MONO = ('https://github.com/JetBrains/JetBrainsMono/releases/download/v2.304/JetBrainsMono-2.304.zip',
        '6f6376c6ed2960ea8a963cd7387ec9d76e3f629125bc33d1fdcd7eb7012f7bbf')
WEIGHTS = {400: 'Regular', 500: 'Medium', 600: 'SemiBold', 700: 'Bold'}
CHARS = ''.join(chr(c) for c in range(0x20, 0x7F))  # printable ASCII: every key label
# the mono UI text: ASCII, Latin-1 and the few typographic marks the page uses (· × — …)
MONO_WEIGHTS = {500: 'Medium', 600: 'SemiBold'}
MONO_CHARS = CHARS + ''.join(chr(c) for c in range(0xA0, 0x100)) + '–—‘’“”…•→↗'

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = ROOT / 'site'


def release(source):
    url, sha = source
    data = urllib.request.urlopen(url).read()
    if hashlib.sha256(data).hexdigest() != sha:
        raise SystemExit('checksum mismatch: ' + url)
    return zipfile.ZipFile(io.BytesIO(data))


def subset(raw, chars, features=True):
    font = TTFont(io.BytesIO(raw))
    opts = Options()
    if not features:
        opts.layout_features = []  # no kerning / calt: glyphs from cmap only
    opts.hinting = False
    opts.name_IDs = ['*']
    opts.flavor = 'woff2'
    sub = Subsetter(opts)
    sub.populate(text=chars)
    sub.subset(font)
    font.flavor = 'woff2'
    return font


def outline(font, ch):
    gs = font.getGlyphSet()
    name = font.getBestCmap().get(ord(ch))
    if name is None:
        return None
    pen = SVGPathPen(gs, ntos=lambda v: str(round(v)))
    gs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))  # font y-up → SVG y-down
    return [gs[name].width, pen.getCommands()]


def main():
    fonts = SITE / 'fonts'
    fonts.mkdir(exist_ok=True)
    z = release(MONO)
    (fonts / 'JetBrainsMono-LICENSE.txt').write_bytes(z.read('OFL.txt'))
    for weight, style in MONO_WEIGHTS.items():
        subset(z.read(f'fonts/webfonts/JetBrainsMono-{style}.woff2'), MONO_CHARS).save(fonts / f'JetBrainsMono-{weight}.woff2')

    z = release(INTER)
    (fonts / 'Inter-LICENSE.txt').write_bytes(z.read('LICENSE.txt'))
    table = {}
    for weight, style in WEIGHTS.items():
        font = subset(z.read(f'web/Inter-{style}.woff2'), CHARS, features=False)
        font.save(SITE / 'fonts' / f'Inter-{weight}.woff2')
        table.setdefault('upm', font['head'].unitsPerEm)
        table.setdefault('w', {})[weight] = {ch: g for ch in CHARS if (g := outline(font, ch))}
    js = ('/* Generated by tools/build-fonts.py from Inter 4.1 (SIL OFL, see fonts/Inter-LICENSE.txt).\n'
          '   Glyph outlines for the flattened SVG export: per weight, char → [advance, path],\n'
          '   in font units (upm), y pointing down, origin on the baseline. Do not edit. */\n'
          'window.KSV_GLYPHS = ' + json.dumps(table, separators=(',', ':'), ensure_ascii=False) + ';\n')
    (SITE / 'glyphs.js').write_text(js, encoding='utf-8')
    for f in sorted((SITE / 'fonts').iterdir()):
        print(f'{f.relative_to(ROOT)}  {f.stat().st_size // 1024} KB')
    print(f'site/glyphs.js  {len(js) // 1024} KB')


if __name__ == '__main__':
    main()
